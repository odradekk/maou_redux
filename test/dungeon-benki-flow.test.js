/**
 * @file run_dungeon / run_benki 的行为基线（#882 拆分巨型函数）。
 *
 * 这两个函数在 #882 里从单个巨型函数拆成一组命名步骤，验收标准是「行为
 * 不变」。既有用例按分支断言，但**随机源的消费顺序**（先掷哪个上界、掷几
 * 次）没有任何用例守着——拆分时若把某段挪到别的条件之后，随机序列就会
 * 错位，只在别的用例里以偶发失败的形式暴露。本文件把四类观测一起钉住：
 *
 *   - rand_calls：注入随机源被请求的上界序列（顺序与条数）；
 *   - prints：输出行逐行全量（含空行）；
 *   - writes：变量写序列（名字 + 值，按发生顺序）；
 *   - waits：等键次数。
 *
 * 期望值是拆分**之前**从原实现采集的；本文件红即说明拆分引入了行为差异。
 * 后续若有意改变这些路径的表现，请同步更新对应条目并在提交说明里写明理由。
 *
 * 随机源一律用定值源（zero / max / no-two / 数值序列），不读 Math.random；
 * 场景表里的 seed 只放该场景需要的那几个变量。
 */

const assert = require('node:assert/strict');
const { test } = require('node:test');

const { create_era_fixture } = require('./helpers/era-fixture');
const { preset_chara_0, join_slave_chara } = require('./helpers/chara');

/** 所有掷骰恒 0（WALK = 0：不推进） */
const zero = () => 0;
/** 所有掷骰恒最大（RAND:N == N-1；WALK = 19 + 6×9 = 73：稳定推进） */
const max = (n) => n - 1;
/** RAND:2 恒 1、其余恒 0：二选一分支全落空（钥匙掷选六连不中） */
const no_two = (n) => (n === 2 ? 1 : 0);

/** 定值序列源：按顺序消费 draws，越界取 0 */
function seq(...draws) {
  let i = 0;
  return (n) => (draws[i++] ?? 0) % n;
}

/** 场景表的 rand 字段 → 随机源 */
function make_rand(spec) {
  if (spec === 'zero') {
    return zero;
  }
  if (spec === 'max') {
    return max;
  }
  if (spec === 'no-two') {
    return no_two;
  }
  return seq(...spec);
}

/** 包一层记录：每次请求的上界按顺序入列 */
function traced(rand) {
  const calls = [];
  return {
    calls,
    rand: (n) => {
      calls.push(n);
      return rand(n);
    },
  };
}

/**
 * run_dungeon 的世界底座：魔王 0 + 勇者 1（阿尔），体力气力全满、
 * 勇者侵攻中（CFLAG:1 = 2）、第 1 层（CFLAG:501）、侵攻度 0。
 */
function dungeon_world(seed) {
  const fixture = create_era_fixture();
  fixture.seed_chara(0, { id: 0, name: '你', callname: '你' });
  fixture.seed_chara(1, { id: 1, name: '阿尔', callname: '阿尔' });
  fixture.era.addCharacter(0);
  fixture.era.addCharacter(1);
  for (const cid of [0, 1]) {
    fixture.store.set(`maxbase:${cid}:0`, 2000);
    fixture.store.set(`maxbase:${cid}:1`, 1000);
    fixture.store.set(`base:${cid}:0`, 2000);
    fixture.store.set(`base:${cid}:1`, 1000);
  }
  fixture.store.set('cflag:1:1', 2);
  fixture.store.set('cflag:1:501', 1);
  for (const [key, value] of Object.entries(seed)) {
    fixture.store.set(key, value);
  }
  return fixture;
}

/** run_benki 的世界底座：魔王 0 + 温妮（31），肉便器、体力气力过门槛 */
function benki_world(seed) {
  const fixture = create_era_fixture();
  preset_chara_0(fixture);
  fixture.era.addCharacter(0);
  join_slave_chara(fixture, 31, '温妮');
  fixture.store.set('talent:31:204', 1);
  fixture.store.set('base:31:0', 500);
  fixture.store.set('base:31:1', 200);
  for (const [key, value] of Object.entries(seed)) {
    fixture.store.set(key, value);
  }
  return fixture;
}

/**
 * 采集一次调用的四类观测。变量写记录在调用前清空——只留被测函数自己的写。
 * @param {object} fixture 夹具
 * @param {(rand: (n: number) => number) => Promise<unknown>} run 被测调用
 * @param {string|number[]} spec 场景表的 rand 字段
 * @param {number} rounds 连续调用次数
 * @returns {Promise<object>} 观测结果
 */
async function capture(fixture, run, spec, rounds) {
  const t = traced(make_rand(spec));
  fixture.var_writes.length = 0;
  for (let i = 0; i < rounds; i += 1) {
    await run(t.rand);
  }
  return {
    rand_calls: t.calls,
    prints: fixture.text_lines(),
    writes: fixture.var_writes.map((w) => [w.name, w.value]),
    waits: fixture.waits.length,
  };
}

