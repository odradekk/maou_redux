/**
 * @file `era.input` 的 rule（数值输入的正则约束）——本模块只有常量与契约说明。
 *
 * 引擎契约（app.asar 渲染层两处逐字，`he()` 收配置、`pe()` 判定提交）：
 *
 *   1. `config.rule` 是**不带锚点**的字符串：渲染层自己拼成
 *      `new RegExp(`^${rule}$`)`。本模块与各调用点因此只写裸正则体。
 *      **拼接不带分组**：`a|b` 会变成 `^a|b$`，首尾锚点只落在第一个与最后
 *      一个分支上（`^(100|[0-4])$` 与 `^100|[0-4]$` 在 `-1` 上给出相反结果
 *      ——后者因为 `[0-4]$` 命中了结尾的 `1`）。凡是含 `|` 的 rule 一律
 *      自己加 `(?:…)`。
 *   2. 判定发生在提交时、对 `String(val)` 做；不合法只弹一条
 *      「输入不合法！输入规范：…」（提示里显示的是 rule 原文——渲染层把
 *      `^` 与 `$` 各剥一个字符再显示，`(?:…)` 不会被吃掉），**不回传**——
 *      游戏层的 `await` 继续等，玩家在同一个输入框里改。所以「不合法时打印
 *      提示、等键、重来」的游戏侧循环换成 rule 之后不可达，随之删除。
 *   3. rule 只在**下一轮**输入生效：成功回传后引擎清空它。
 *   4. rule 一旦设置就**取代**按钮白名单（渲染层按「rule 是 RegExp 还是数组」
 *      二选一）：本轮打印过的按钮编号也必须落在 rule 里，否则连按钮都点不动。
 *      这也是本仓库只在「没有按钮的输入轮」上写 rule 的原因——有按钮的轮次
 *      由白名单负责，写 rule 反而会把按钮集之外的值放进来。
 *   5. 空提交引擎本来就不受理（渲染层的空检查），rule 不必再管空串。
 */

/**
 * 数量输入的 rule：任意位数的非负整数（含 0）。
 *
 * 不用 `0|[1-9][0-9]*` 是给玩家留余地：`007` 这类前导零也算合法输入，
 * 引擎的 `getNumber` 会把它归一成 7。上界不写进正则——数量上限取自当前
 * 资金、库存这类活数据，写成正则既拼不出可读的「输入规范」提示，也会在
 * 上限变化时失效；越界仍由调用点按活数据判定。
 */
const COUNT_RULE = '[0-9]+';

module.exports = { COUNT_RULE };
