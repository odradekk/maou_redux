/**
 * 指令的静态名——旧静态名表 traincommandname 的等价物，也是内建指令列表
 * 与「上次的调教指令」行显示的文本。
 *
 * 引擎装载名字表时把名称列整体转小写（app.asar 的装载循环
 * `o.map(e => (e[1] = toLowerCase(e[1]), e))`），玩家看到的正是转小写后的
 * 文本，全角拉丁也有小写形（'３Ｐ' → '３ｐ'）。名字表换成常量后这层归一
 * 没了，这里复现它：显示逐字不变。表里的名称保持原样（'野外ＰＬＡＹ'），
 * 转小写只在读显示名时做——别名层（read_train_name）存的是原样，两条渲染
 * 路径的文本与改动前一致。
 *
 * 名称里的字母一律全角（#822）：半角字母转小写会退化成半角（'野外PLAY' →
 * '野外play'），全角转小写仍是全角（'野外ＰＬＡＹ' → '野外ｐｌａｙ'），
 * 与 yml 名字表那边的口径一致。
 *
 * @param {number} id 指令编号
 * @returns {string} 不可直选的编号（高级 COM、空号、乱数）返回空串——旧
 *   代码对表外编号不读名字表
 */
function train_command_name(id) {
  return (TRAIN_COMMAND[id] ?? '').toLowerCase();
}

