/**
 * @file 换屏入口：每一屏开始绘制前整屏清空（ADR-0009「每一屏开始前整屏
 * 清空，不保留历史」；术语见 CONTEXT.md「一屏/换屏」）。
 *
 * 引擎渲染层每次输入都把全部历史行重新渲染并滚到底部，耗时与历史行数
 * 成正比；引擎自带的行数上限读错配置路径、永远不生效（实测见 issue #720）。
 * 只追加不清屏的游戏因此越玩越慢，只能由游戏侧在每一屏开始时清屏。
 *
 * 这里只做整屏清空（无参 era.clear()），不补等键：引擎的 waitAnyKey 按
 * 「上次输入之后有没有新输出」决定等不等，而菜单输入的回显本身就算一次
 * 输出——在换屏里无条件等键会让每次菜单选择后都多一次按键。换屏之前，
 * 上一次菜单选择之后产生的输出必须已经被玩家按键确认过；哪条路径缺等键，
 * 就在那段输出的末尾补，漏补的路径由测试夹具的未读输出检查
 *（era-fixture.js 的 unread_output_clears）在端到端测试里报出。
 *
 * 右键快进遇 clear 会在清屏前强制等一次按键并退出快进（ADR-0003）：按
 * 本规则，快进在每一屏开始时停一次，是有意的翻页行为。
 */

const era = require('#/era-electron');

/**
 * 换屏：整屏清空，随后由调用方绘制新一屏。
 * @returns {Promise<number>} 清屏后的行数（整屏清空，恒 0）
 */
async function change_screen() {
  return await era.clear();
}

module.exports = { change_screen };
